CREATE OR REPLACE FUNCTION landscape.refresh_financial_summary_res()
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM 1 FROM pg_matviews WHERE schemaname = 'landscape' AND matviewname = 'financial_summary_res';
