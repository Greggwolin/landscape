    REFRESH MATERIALIZED VIEW CONCURRENTLY landscape.financial_summary_res;
  ELSE
    RAISE NOTICE 'Cannot refresh landscape.financial_summary_res: materialized view does not exist';
  END IF;
END;
$$;

