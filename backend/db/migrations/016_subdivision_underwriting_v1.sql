-- Section G: Summary / Outputs Materialized View
-- ============================================================================
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_matviews
    WHERE schemaname = 'landscape' AND matviewname = 'financial_summary_res'
  ) THEN
    EXECUTE $mv$
      CREATE MATERIALIZED VIEW landscape.financial_summary_res AS
      SELECT
        p.project_id,
        p.parcel_id,
        COALESCE(SUM(r.period_revenue), 0)::NUMERIC(16,2)              AS lot_revenue_total,
        COALESCE(SUM(CASE WHEN b.include_in_per_lot_infra_flag THEN b.amount ELSE 0 END), 0)::NUMERIC(16,2) AS direct_cogs_infra,
        0::NUMERIC(16,2) AS direct_cogs_land,
        0::NUMERIC(16,2) AS direct_cogs_lot_financing,
        0::NUMERIC(16,2) AS total_overhead_exp,
        COALESCE(SUM(d.idc_capitalized), 0)::NUMERIC(16,2) AS idc_total,
        now() AS snapshot_ts
      FROM (
        SELECT DISTINCT project_id, parcel_id FROM landscape.project_parcel_boundaries
      ) p
      LEFT JOIN landscape.tbl_revenue_schedule_res r
        ON r.project_id = p.project_id AND r.parcel_id = p.parcel_id
      LEFT JOIN landscape.tbl_budget b
        ON b.project_id = p.project_id AND b.parcel_id = p.parcel_id
      LEFT JOIN landscape.financial_draws d
        ON d.project_id = p.project_id AND d.parcel_id = p.parcel_id
      GROUP BY p.project_id, p.parcel_id;
    $mv$;
    RAISE NOTICE 'Created materialized view landscape.financial_summary_res';
  ELSE
    RAISE NOTICE 'Skipping creation of landscape.financial_summary_res (already exists)';
  END IF;
END$$;

